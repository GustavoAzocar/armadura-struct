// Independent deterministic DXF fixtures shared by both applications; no production code.
export function lineScene(count, offset = 0, precision = false) {
  return Array.from({ length: count }, (_, i) => {
    const x = offset + (i % (precision ? 10 : 200)) * (precision ? 10 : 160);
    const y =
      offset + Math.floor(i / (precision ? 10 : 200)) * (precision ? 10 : 240);
    return [
      0,
      'LINE',
      8,
      'COMMON',
      10,
      x,
      20,
      y,
      11,
      x + (precision ? 3 : 100),
      21,
      y + (precision ? 2 : 60),
    ];
  });
}
